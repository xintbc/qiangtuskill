/* 展开成查表对象：RAID_ITEMS[id] = {id,名,图标,类,稀有,价,重,叠,格:[w,h],容,载,收,口径,描,务} */
var RAID_ITEMS = (function () {
  var o = {}, i, r, d;
  for (i = 0; i < _物品表.length; i++) {
    r = _物品表[i];
    d = {
      id: r[0], 名: r[1], 图标: r[2], 类: r[3], 稀有: r[4] | 0,
      价: r[5] | 0, 重: +r[6], 叠: r[7] | 0, 格: [r[8] | 0, r[9] | 0]
    };
    var x = r[10];
    if (x) {
      if (x.容) { d.容 = x.容; d.载 = x.载 || 0; }
      if (x.收) d.收 = x.收;
      if (x.口径) d.口径 = x.口径;
      if (x.描) d.描 = x.描;
      if (x.单限) d.单限 = x.单限;
      if (x.务) d.务 = 1;
      /* 护甲耐久 / 修补：以前这里根本没展开，导致 eq_armor 的耐、修补包的修甲
         全是 undefined —— 表现就是"护甲无效、修补包只当绷带用"。 */
      if (x.耐) d.耐 = x.耐;
      if (x.减) d.减 = x.减;
      if (x.修甲) d.修甲 = x.修甲;
      if (x.修头) d.修头 = x.修头;
      if (x.回血) d.回血 = x.回血;
    }
    /* 任务物一律不可出售、不可堆叠 */
    if (d.类 === '任务') { d.务 = 1; d.叠 = 1; }
    o[d.id] = d;
  }
  return o;
})();

