/* ============================================================================
   网页视图.h —— 内嵌 WebView2 控件的薄封装（纯 C 调 COM）
   ----------------------------------------------------------------------------
   为什么不用"打开系统 Edge 的 --app 窗口"：那是**调用本地浏览器**，
   会有自己的进程/图标/快捷键，手机上更无从谈起。这里要的是**内嵌**：
   浏览器内核以子窗口形式长在我们的窗口里，外面套的是游戏自己的壳。

   加载方式：把本地 `多文件版` 目录**映射成一个 https 虚拟站点**
   （https://game.example/），然后导航过去。这样：
     · 不需要起 HTTP 服务，也不需要 file://（file:// 下有些浏览器 API 会被禁用）
     · 页面里的相对路径、ES 模块、WebGL、字体全部按正常 https 走
     · 完全离线（Three.js 等都在本地 libs/ 里，不访问外网）
   ========================================================================= */
#ifndef WEBVIEW_HOST_H
#define WEBVIEW_HOST_H

#include <windows.h>

/* 初始化（异步）。根目录＝`多文件版` 的绝对路径；服务器地址可空。
   成功后会自动导航到 index.html。返回 FALSE 表示连内核都没起来（缺运行时）。 */
BOOL 网页视图_启动(HWND 父窗口, const wchar_t *根目录, const char *服务器地址);

/* 设置初始导航路径（在 网页视图_启动 之前调；默认 L"index.html"）。
   版本内启动器用它把账号参数拼在 index.html 后面。 */
void 网页视图_设初始路径(const wchar_t *相对路径);

/* 控件是否已经准备好（导航完成前也可以调，内部会自己等） */
BOOL 网页视图_就绪(void);

/* 窗口尺寸变了 → 让内核铺满客户区 */
void 网页视图_铺满(void);

/* 指定内核占用的矩形（客户端顶部有一条工具条，内容区要避开它） */
void 网页视图_设区域(int 左, int 上, int 宽, int 高);

/* 导航到指定路径（相对虚拟站点根），例如 L"index.html?solo=1" */
void 网页视图_转到(const wchar_t *相对路径);

/* 重新加载当前页 */
void 网页视图_刷新(void);

/* 执行一段 JS（用于"帮助"浮层之类；失败静默） */
void 网页视图_执行JS(const wchar_t *js);

/* 把页面自检结果（写在 document.title 里）记进启动日志。客户端定时器每秒调一次即可。 */
void 网页视图_自检日志(void);

/* 关掉内核（退出前调） */
void 网页视图_关闭(void);

#endif
