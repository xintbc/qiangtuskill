/* ============================================================================
   本地服务.h —— 内置迷你 HTTP 服务器（只服务游戏目录，监听 127.0.0.1）
   ----------------------------------------------------------------------------
   用途：让 WebView2 用 `http://127.0.0.1:端口/` 当页面源，而不是 https 虚拟主机。
   为什么：页面是 http 源时，游戏里连服务器才能用明文 ws://（https 源会被强行拼成
   wss:// 并被混合内容策略拦掉）→ 这是"客户端连不上服务器"的根因。
   127.0.0.1 同时被浏览器视为安全上下文，麦克风 / IndexedDB 照样可用。
   ========================================================================= */
#ifndef LOCAL_SERVICE_H
#define LOCAL_SERVICE_H

#include <windows.h>

/* 首选端口（后面 40 个依次尝试；上次用过的端口会记在 配置\端口.txt 里优先复用，
   端口不变 = 页面源不变 = localStorage 存档延续） */
#define 本地服务默认端口 39001

/* 启动服务。根目录＝要对外提供的文件夹；配置目录＝存「端口.txt」的位置（可为 NULL）。
   返回实际端口（0 表示失败）。 */
int  本地服务_启动(const WCHAR *根目录, const WCHAR *配置目录);

/* 当前端口（0 表示没起来） */
int  本地服务_端口(void);

/* 关掉（退出前调） */
void 本地服务_停止(void);

#endif
