const CRLF原样 = (fs.readFileSync(SRC, 'utf8').match(/\r\n/g) || []).length > 100;
let S = fs.readFileSync(SRC, 'utf8').replace(/\r\n/g, '\n');
const ms = [...S.matchAll(/<script([^>]*)>([\s\S]*?)<\/script>/g)];
if (ms.length !== 3) { console.log('❌ script 段数 = ' + ms.length + '（应 3）'); process.exit(1); }
const code = ms[2][2];
const tail = S.slice(ms[2].index + ms[2][0].length);
const 行 = code.split('\n');

const 回退 = new Set(['js/42_英雄_特效一.js', 'js/43_英雄_特效二.js', 'js/44_英雄_世界与远端.js']);
const 纯分隔线 = /^\s*\/\*\s*=+\s*$/;
const 起点 = [];
for (const [name, 锚] of 表) {
  if (锚 === null) { 起点.push(0); continue; }
  const idx = [];
  行.forEach((l, i) => { if (l.trim() === 锚) idx.push(i); });
  if (idx.length !== 1) { console.log('❌ 锚点不唯一（' + idx.length + ' 次）：' + name); process.exit(1); }
  let i = idx[0];
  if (回退.has(name)) {
    while (i > 0 && !纯分隔线.test(行[i])) i--;
    if (!纯分隔线.test(行[i])) { console.log('❌ 回退注释头失败：' + name); process.exit(1); }
  }
  起点.push(i);
}
for (let i = 1; i < 起点.length; i++) {
  if (起点[i] <= 起点[i - 1]) { console.log('❌ 锚点顺序不对：' + 表[i][0]); process.exit(1); }
}

const 段s = [];
let 变了 = 0;
for (let i = 0; i < 表.length; i++) {
  const a = 起点[i], b = (i + 1 < 表.length) ? 起点[i + 1] : 行.length;
  const 原段 = 行.slice(a, b).join('\n');
  let js = fs.readFileSync(OUT + '/' + 表[i][0], 'utf8').replace(/\r\n/g, '\n').replace(/\s+$/, '');
  /* 只比「去掉尾部空行」的内容：分片文件末尾本来就不带空行，
     而 HTML 里两段之间会留空行 —— 那是边界格式，不是内容差异，不能算改过。 */
  if (js === 原段.replace(/\s+$/, '')) {
    段s.push(原段);                  /* 没动过 → 原样保留，一个字节都不改 */
    continue;
  }
  变了++;
  /* 找出第一处差异行，方便确认改的是不是自己想改的地方 */
  const A = 原段.replace(/\s+$/, '').split('\n'), B = js.split('\n');
  let k = 0; while (k < Math.min(A.length, B.length) && A[k] === B[k]) k++;
  console.log('  ~ ' + 表[i][0] + '  (' + A.length + '→' + B.length + ' 行, 首个差异在第 ' + (k + 1) + ' 行)');
  段s.push(js + '\n');               /* 补回尾部空行，保持原有分段格式 */
}
const 新code = 段s.join('\n');

/* 安全检查：3 个 script 段必须还是 3 个；新代码里不能出现裸的 </script> */
if ((新code.match(/<\/script>/g) || []).length) { console.log('❌ 新代码里出现 </script>，会截断页面'); process.exit(1); }

const 开标签 = ms[2][0].slice(0, ms[2][0].indexOf('>') + 1);
const 新S = S.slice(0, ms[2].index) + 开标签 + 新code + '</script>' + tail;
const 输出 = CRLF原样 ? 新S.replace(/\n/g, '\r\n') : 新S;

console.log('分片共 ' + 表.length + ' 个，其中 ' + 变了 + ' 个与唯一源不同。');
console.log('唯一源 ' + (S.length / 1024 | 0) + 'KB → ' + (新S.length / 1024 | 0) + 'KB');
if (!写回) { console.log('（dry-run，加 --写 才写回）'); process.exit(0); }
fs.writeFileSync(SRC, 输出, 'utf8');
console.log('✅ 已写回唯一源');
const 验 = fs.readFileSync(SRC, 'utf8');
